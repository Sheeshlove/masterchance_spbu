@dataclass
class Block:
    """Кусок текста: абзац, список или выделенная врезка."""
    kind: str                                  # "p" | "list" | "note"
    text: str = ""
    items: list[str] = field(default_factory=list)


@dataclass
class Section:
    title: str
    blocks: list[Block]


def p(text: str) -> Block:
    return Block("p", text=text)


def ul(*items: str) -> Block:
    return Block("list", items=list(items))


def note(text: str) -> Block:
    return Block("note", text=text)


